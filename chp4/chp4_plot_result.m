function [maes, bmt_stds, all_norm_bmt] = summary_result (map_save_folders)
    maes = [];
    bmt_stds = [];
    all_norm_bmt = [];

    for save_folder = map_save_folders
        mae = load(save_folder + "mae.mat").mae;
        bmt_std = load(save_folder + "bmt_std.mat").bmt_std;
        norm_bmts = load(save_folder + "norm_winners.mat").norm_winners;
        
        maes = [maes; mae];
        bmt_stds = [bmt_stds; bmt_std];
        all_norm_bmt = [all_norm_bmt; reshape(norm_bmts, [], 1)];
    end

    all_norm_bmt = reshape(all_norm_bmt, [], 1);
end

